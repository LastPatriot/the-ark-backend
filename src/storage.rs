use std::path::{Path, PathBuf};

use crate::{config::Config, error::AppError};

const MAX_NAME_CHARS: usize = 255;
/// Leaves room for the `__vN` / `-xxxxxx` suffixes within common 255-byte limits.
const MAX_DISK_NAME_BYTES: usize = 200;

/// `ARK_DATA_DIR/files`. Every user file lives below it.
pub fn files_root(cfg: &Config) -> PathBuf {
    cfg.data_dir.join("files")
}

/// `ARK_DATA_DIR/uploads/<id>.part`. `upload_id` is always server-generated.
pub fn part_path(cfg: &Config, upload_id: &str) -> PathBuf {
    debug_assert!(is_plain_component(upload_id));
    cfg.data_dir
        .join("uploads")
        .join(format!("{upload_id}.part"))
}

/// `ARK_DATA_DIR/previews/<name>`. Preview names are server-generated (`<file_id>_<kind>.jpg`).
pub fn preview_path(cfg: &Config, name: &str) -> PathBuf {
    debug_assert!(is_plain_component(name));
    cfg.data_dir.join("previews").join(name)
}

/// Creates the on-disk directory for a folder. `disk_dir` is always generated by the
/// server (the folder id), never taken from user input.
pub async fn create_folder_dir(cfg: &Config, disk_dir: &str) -> std::io::Result<PathBuf> {
    debug_assert!(is_plain_component(disk_dir));
    let dir = files_root(cfg).join(disk_dir);
    tokio::fs::create_dir_all(&dir).await?;
    Ok(dir)
}

/// Resolves `files/<disk_dir>/<disk_name>`, creating the folder directory if needed.
/// The canonicalized result must stay inside the files root; anything else is a bug
/// (or tampering) and is reported as a 500.
pub async fn checked_path(
    cfg: &Config,
    disk_dir: &str,
    disk_name: &str,
) -> Result<PathBuf, AppError> {
    let escape = |what: &str| {
        tracing::error!(disk_dir, disk_name, "{what}: path escapes the files root");
        AppError::Internal(anyhow::anyhow!("unsafe storage path"))
    };
    if !is_plain_component(disk_dir) || !is_plain_component(disk_name) {
        return Err(escape("bad component"));
    }
    let root = tokio::fs::canonicalize(files_root(cfg)).await?;
    let dir = create_folder_dir(cfg, disk_dir).await?;
    let dir = tokio::fs::canonicalize(dir).await?;
    if !dir.starts_with(&root) || dir == root {
        return Err(escape("folder dir"));
    }
    let path = dir.join(disk_name);
    // An existing entry may be a symlink; check where it really points.
    if let Ok(real) = tokio::fs::canonicalize(&path).await
        && !real.starts_with(&dir)
    {
        return Err(escape("file"));
    }
    Ok(path)
}

/// A single path component with no separators and no special meaning.
fn is_plain_component(s: &str) -> bool {
    !s.is_empty()
        && s != "."
        && s != ".."
        && !s.contains(['/', '\\', '\0'])
        && Path::new(s).components().count() == 1
}

/// Display name for an uploaded file: last path component of what the client sent
/// (browsers may send `C:\fakepath\x.jpg`), without control characters.
pub fn display_name(raw: &str) -> Option<String> {
    let last = raw.rsplit(['/', '\\']).next().unwrap_or("");
    let cleaned: String = last
        .chars()
        .filter(|c| !c.is_control())
        .take(MAX_NAME_CHARS)
        .collect();
    let cleaned = cleaned.trim();
    (!cleaned.is_empty() && cleaned != "." && cleaned != "..").then(|| cleaned.to_string())
}

/// Name safe to create on Windows, macOS and Linux: no separators, reserved characters,
/// control characters, leading/trailing dots or spaces, or reserved device names.
pub fn sanitize_name(name: &str) -> String {
    let mut out: String = name
        .chars()
        .map(|c| match c {
            '<' | '>' | ':' | '"' | '/' | '\\' | '|' | '?' | '*' => '_',
            c if c.is_control() => '_',
            c => c,
        })
        .collect();
    out = out.trim_matches(|c| c == '.' || c == ' ').to_string();
    if out.is_empty() {
        out = "file".into();
    }

    let (stem, _) = split_ext(&out);
    let device = stem.split('.').next().unwrap_or("").to_ascii_uppercase();
    let reserved = matches!(device.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        || ((device.starts_with("COM") || device.starts_with("LPT"))
            && device.len() == 4
            && device.as_bytes()[3].is_ascii_digit());
    if reserved {
        out = format!("_{out}");
    }

    if out.len() > MAX_DISK_NAME_BYTES {
        let (stem, ext) = split_ext(&out);
        let ext = if ext.len() <= 16 { ext } else { "" };
        let mut cut = MAX_DISK_NAME_BYTES - ext.len();
        while !stem.is_char_boundary(cut.min(stem.len())) {
            cut -= 1;
        }
        out = format!("{}{ext}", &stem[..cut.min(stem.len())]);
    }
    out
}

/// `cover.psd` v1 -> `cover.psd`, v2 -> `cover__v2.psd`.
pub fn versioned_disk_name(display: &str, version: i64) -> String {
    let safe = sanitize_name(display);
    if version <= 1 {
        return safe;
    }
    let (stem, ext) = split_ext(&safe);
    format!("{stem}__v{version}{ext}")
}

/// Adds a short tag before the extension, used when a disk name is already taken.
pub fn tagged_disk_name(disk_name: &str, tag: &str) -> String {
    let (stem, ext) = split_ext(disk_name);
    format!("{stem}-{tag}{ext}")
}

/// Splits `name.ext` into (`name`, `.ext`). Dotfiles have no extension.
fn split_ext(name: &str) -> (&str, &str) {
    match name.rfind('.') {
        Some(i) if i > 0 => (&name[..i], &name[i..]),
        _ => (name, ""),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn display_names() {
        assert_eq!(
            display_name("C:\\fakepath\\photo.jpg").as_deref(),
            Some("photo.jpg")
        );
        assert_eq!(display_name("../../etc/passwd").as_deref(), Some("passwd"));
        assert_eq!(display_name("a\u{0}b\nc.txt").as_deref(), Some("abc.txt"));
        assert_eq!(display_name("dir/.."), None);
        assert_eq!(display_name("   "), None);
    }

    #[test]
    fn sanitizes_for_disk() {
        assert_eq!(sanitize_name("../secret"), "_secret");
        assert_eq!(sanitize_name("a/b\\c:d*e?.txt"), "a_b_c_d_e_.txt");
        assert_eq!(sanitize_name(".."), "file");
        assert_eq!(sanitize_name("  .hidden. "), "hidden");
        assert_eq!(sanitize_name("CON"), "_CON");
        assert_eq!(sanitize_name("con.txt"), "_con.txt");
        assert_eq!(sanitize_name("lpt1.tar.gz"), "_lpt1.tar.gz");
        assert_eq!(sanitize_name("console.txt"), "console.txt");
        let long = format!("{}.jpg", "é".repeat(300));
        let s = sanitize_name(&long);
        assert!(s.len() <= MAX_DISK_NAME_BYTES && s.ends_with(".jpg"));
    }

    #[test]
    fn version_names() {
        assert_eq!(versioned_disk_name("cover.psd", 1), "cover.psd");
        assert_eq!(versioned_disk_name("cover.psd", 2), "cover__v2.psd");
        assert_eq!(versioned_disk_name("README", 3), "README__v3");
        assert_eq!(
            tagged_disk_name("cover__v2.psd", "ab12cd"),
            "cover__v2-ab12cd.psd"
        );
    }

    #[test]
    fn plain_components() {
        assert!(is_plain_component("019a2b3c-4d5e"));
        assert!(is_plain_component("photo.jpg"));
        for bad in ["", ".", "..", "a/b", "a\\b", "/etc", "a\0b"] {
            assert!(!is_plain_component(bad), "{bad:?}");
        }
    }

    #[tokio::test]
    async fn checked_path_stays_inside_root() {
        let tmp = std::env::temp_dir().join(format!("ark-test-{}", crate::util::new_id()));
        std::fs::create_dir_all(tmp.join("files")).unwrap();
        let cfg = Config::for_tests(tmp.clone());
        let ok = checked_path(&cfg, "folder1", "a.txt").await.unwrap();
        assert!(ok.ends_with("folder1/a.txt"));
        assert!(checked_path(&cfg, "..", "a.txt").await.is_err());
        assert!(checked_path(&cfg, "folder1", "../../x").await.is_err());
        assert!(checked_path(&cfg, "folder1", "..").await.is_err());

        #[cfg(unix)]
        {
            std::os::unix::fs::symlink("/etc/hosts", tmp.join("files/folder1/link")).unwrap();
            assert!(checked_path(&cfg, "folder1", "link").await.is_err());
            std::os::unix::fs::symlink("/tmp", tmp.join("files/evil")).unwrap();
            assert!(checked_path(&cfg, "evil", "a.txt").await.is_err());
        }
        std::fs::remove_dir_all(tmp).unwrap();
    }
}
